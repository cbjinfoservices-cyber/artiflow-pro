-- Purge automatique des données arrivées à échéance (durées annoncées sur /rgpd).
--
-- Chaque nuit, la base supprime elle-même :
--   - les inscriptions jamais confirmées depuis plus de 30 jours (compte sans profil ni fiche intervenant) ;
--   - les journaux techniques des envois et des tests de plus de 12 mois ;
--   - les traces de demandes de suppression de compte terminées depuis plus de 5 ans.
-- Elle déclenche aussi la fonction purger-comptes-supprimes (effacement des comptes dont le délai de
-- 30 jours est écoulé), pour que cet engagement ne dépende pas d'un service de tâches externe.
-- Chaque passage est consigné dans purges_journal (preuve de l'application des durées).

CREATE EXTENSION IF NOT EXISTS pg_cron;
CREATE EXTENSION IF NOT EXISTS pg_net WITH SCHEMA extensions;

CREATE TABLE public.purges_journal (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  executee_le timestamptz NOT NULL DEFAULT now(),
  details jsonb NOT NULL DEFAULT '{}'::jsonb
);
ALTER TABLE public.purges_journal ENABLE ROW LEVEL SECURITY;
CREATE POLICY purges_journal_lecture_gestionnaire ON public.purges_journal FOR SELECT TO authenticated
  USING (public.est_gestionnaire());

CREATE OR REPLACE FUNCTION public.purger_donnees_expirees()
RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  bilan jsonb := '{}'::jsonb;
  nombre integer;
  compte record;
  comptes_supprimes integer := 0;
  t text;
BEGIN
  -- 1) Inscriptions jamais confirmées (adresse email non validée) depuis plus de 30 jours.
  FOR compte IN
    SELECT u.id FROM auth.users u
    WHERE u.email_confirmed_at IS NULL
      AND u.created_at < now() - interval '30 days'
      AND NOT EXISTS (SELECT 1 FROM public.profiles p WHERE p.id = u.id)
      AND NOT EXISTS (SELECT 1 FROM public.intervenants i WHERE i.compte_id = u.id)
  LOOP
    BEGIN
      DELETE FROM auth.users WHERE id = compte.id;
      comptes_supprimes := comptes_supprimes + 1;
    EXCEPTION WHEN OTHERS THEN
      -- Un compte encore référencé ailleurs est laissé en place : la purge suivante réessaiera.
      NULL;
    END;
  END LOOP;
  bilan := bilan || jsonb_build_object('inscriptions_non_confirmees', comptes_supprimes);

  -- 2) Journaux techniques de plus de 12 mois.
  FOREACH t IN ARRAY ARRAY[
    'envoi_fournisseur_historique', 'email_test_historique', 'rejeux_blanc_historique', 'envois_auto_tests',
    'reessais_envoi_historique', 'test_paiement_blanc_historique', 'test_abonnement_essai_historique'
  ] LOOP
    EXECUTE format('DELETE FROM public.%I WHERE created_at < now() - interval ''12 months''', t);
    GET DIAGNOSTICS nombre = ROW_COUNT;
    bilan := bilan || jsonb_build_object(t, nombre);
  END LOOP;
  DELETE FROM public.diagnostic_email_historique WHERE checked_at < now() - interval '12 months';
  GET DIAGNOSTICS nombre = ROW_COUNT;
  bilan := bilan || jsonb_build_object('diagnostic_email_historique', nombre);

  -- 3) Traces de suppression de compte terminées (effectuées ou annulées) depuis plus de 5 ans.
  DELETE FROM public.suppressions_compte
  WHERE statut <> 'programmee'
    AND coalesce(supprimee_le, annulee_le, updated_at, demandee_le) < now() - interval '5 years';
  GET DIAGNOSTICS nombre = ROW_COUNT;
  bilan := bilan || jsonb_build_object('suppressions_compte', nombre);

  -- 4) Le journal des purges lui-même : 5 ans.
  DELETE FROM public.purges_journal WHERE executee_le < now() - interval '5 years';

  INSERT INTO public.purges_journal (details) VALUES (bilan);
  RETURN bilan;
END $$;

REVOKE ALL ON FUNCTION public.purger_donnees_expirees() FROM PUBLIC, anon, authenticated;

