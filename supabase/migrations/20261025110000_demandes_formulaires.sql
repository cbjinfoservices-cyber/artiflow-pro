-- Formulaires publics du site (démo, contact, candidature, alerte podcast) : les demandes sont
-- enregistrées ici par la fonction recevoir-formulaire, au lieu du service de formulaires de Readdy.
-- Aucun accès direct pour les visiteurs : seule la fonction (clé service) écrit, seuls les
-- gestionnaires lisent.

CREATE TABLE public.demandes_formulaires (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  type text NOT NULL CHECK (type IN ('demo', 'contact', 'candidature', 'podcast')),
  email text NOT NULL,
  nom text,
  telephone text,
  champs jsonb NOT NULL DEFAULT '{}'::jsonb,
  traitee boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX demandes_formulaires_email_idx ON public.demandes_formulaires (lower(email), created_at);
CREATE INDEX demandes_formulaires_created_at_idx ON public.demandes_formulaires (created_at);

ALTER TABLE public.demandes_formulaires ENABLE ROW LEVEL SECURITY;
CREATE POLICY demandes_formulaires_gestionnaire ON public.demandes_formulaires FOR ALL TO authenticated
  USING (public.est_gestionnaire()) WITH CHECK (public.est_gestionnaire());

-- Purge : ajout des demandes de formulaires aux durées appliquées chaque nuit.
--   - démo, contact, alerte podcast : 3 ans ;
--   - candidature non retenue : 2 ans (recommandation de la CNIL).
CREATE OR REPLACE FUNCTION public.purger_donnees_expirees()
RETURNS jsonb
LANGUAGE plpgsql SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  bilan jsonb := '{}'::jsonb;
  nombre integer;
  compte record;
  comptes_supprimes integer := 0;
  t text;
BEGIN
  -- 1) Inscriptions jamais confirmées (adresse email non validée) depuis plus de 30 jours.
  FOR compte IN
    SELECT u.id FROM auth.users u
    WHERE u.email_confirmed_at IS NULL
      AND u.created_at < now() - interval '30 days'
      AND NOT EXISTS (SELECT 1 FROM public.profiles p WHERE p.id = u.id)
      AND NOT EXISTS (SELECT 1 FROM public.intervenants i WHERE i.compte_id = u.id)
  LOOP
    BEGIN
      DELETE FROM auth.users WHERE id = compte.id;
      comptes_supprimes := comptes_supprimes + 1;
    EXCEPTION WHEN OTHERS THEN
      NULL;
    END;
  END LOOP;
  bilan := bilan || jsonb_build_object('inscriptions_non_confirmees', comptes_supprimes);

  -- 2) Journaux techniques de plus de 12 mois.
  FOREACH t IN ARRAY ARRAY[
    'envoi_fournisseur_historique', 'email_test_historique', 'rejeux_blanc_historique', 'envois_auto_tests',
    'reessais_envoi_historique', 'test_paiement_blanc_historique', 'test_abonnement_essai_historique'
  ] LOOP
    EXECUTE format('DELETE FROM public.%I WHERE created_at < now() - interval ''12 months''', t);
    GET DIAGNOSTICS nombre = ROW_COUNT;
    bilan := bilan || jsonb_build_object(t, nombre);
  END LOOP;
  DELETE FROM public.diagnostic_email_historique WHERE checked_at < now() - interval '12 months';
  GET DIAGNOSTICS nombre = ROW_COUNT;
  bilan := bilan || jsonb_build_object('diagnostic_email_historique', nombre);

  -- 3) Demandes reçues par les formulaires du site.
  DELETE FROM public.demandes_formulaires
  WHERE (type = 'candidature' AND created_at < now() - interval '2 years')
     OR (type <> 'candidature' AND created_at < now() - interval '3 years');
  GET DIAGNOSTICS nombre = ROW_COUNT;
  bilan := bilan || jsonb_build_object('demandes_formulaires', nombre);

  -- 4) Traces de suppression de compte terminées (effectuées ou annulées) depuis plus de 5 ans.
  DELETE FROM public.suppressions_compte
  WHERE statut <> 'programmee'
    AND coalesce(supprimee_le, annulee_le, updated_at, demandee_le) < now() - interval '5 years';
  GET DIAGNOSTICS nombre = ROW_COUNT;
  bilan := bilan || jsonb_build_object('suppressions_compte', nombre);

  -- 5) Le journal des purges lui-même : 5 ans.
  DELETE FROM public.purges_journal WHERE executee_le < now() - interval '5 years';

  INSERT INTO public.purges_journal (details) VALUES (bilan);
  RETURN bilan;
END $$;

REVOKE ALL ON FUNCTION public.purger_donnees_expirees() FROM PUBLIC, anon, authenticated;
