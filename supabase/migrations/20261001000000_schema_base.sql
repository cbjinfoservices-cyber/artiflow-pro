-- 5. Index sur les colonnes de propriétaire et les liens (les règles d'accès filtrent dessus à chaque requête)
DO $$
DECLARE r record;
BEGIN
  FOR r IN
    SELECT c.table_name, c.column_name
    FROM information_schema.columns c
    WHERE c.table_schema = 'public'
      AND c.column_name IN ('user_id', 'artisan_id', 'client_id', 'devis_id', 'chantier_id', 'intervenant_id',
                            'creneau_id', 'relance_id', 'facture_id', 'abonnement_id', 'order_id', 'product_id')
      AND NOT EXISTS (
        SELECT 1 FROM pg_index i
        JOIN pg_attribute a ON a.attrelid = i.indrelid AND a.attnum = i.indkey[0]
        WHERE i.indrelid = format('public.%I', c.table_name)::regclass AND a.attname = c.column_name
      )
  LOOP
    EXECUTE format('CREATE INDEX %I ON public.%I (%I)', r.table_name || '_' || r.column_name || '_idx', r.table_name, r.column_name);
  END LOOP;
END $$;
